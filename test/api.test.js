import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir,mkdtemp,rm} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import net from 'node:net';
import {once} from 'node:events';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
test('API persists inventory, imports atomically, scans only real targets, and exports safe reports',async t=>{
  await mkdir(path.join(root,'data'),{recursive:true});
  const temp=await mkdtemp(path.join(root,'data','test-'));
  const child=spawn(process.execPath,['server.js'],{cwd:root,env:{...process.env,PORT:'0',INFRACHECK_DB:path.join(temp,'test.db')},stdio:['ignore','pipe','pipe']});
  t.after(async()=>{child.kill();await once(child,'exit').catch(()=>{});await rm(temp,{recursive:true,force:true});});
  let url='';
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error('Server startup timed out')),10000);child.once('error',reject);child.stdout.on('data',b=>{const match=String(b).match(/http:\/\/127\.0\.0\.1:\d+/);if(match){url=match[0];clearTimeout(timer);resolve();}});});
  async function request(route,method='GET',body,headers={}){const response=await fetch(url+route,{method,headers:{...(body?{'Content-Type':'application/json'}:{}),...headers},body:body?JSON.stringify(body):undefined});const content=await response.text();return {status:response.status,body:response.headers.get('content-type')?.startsWith('application/json')?JSON.parse(content):content};}
  const initial=(await request('/api/state')).body;
  assert.equal(initial.servers.length,12);
  assert.equal((await request('/')).status,200);
  assert.equal((await request('/api/state','GET',undefined,{Origin:'https://untrusted.example'})).status,403);
  assert.equal((await request('/api/servers/dc-01/scan','POST')).status,400);
  const rack={id:'test-rack',name:'Test rack',location:'Test lab',units:42,maxWatts:5000};
  assert.equal((await request('/api/racks','POST',rack)).status,201);
  const listener=net.createServer(socket=>socket.end());listener.listen(0,'127.0.0.1');await once(listener,'listening');t.after(()=>listener.close());
  const device={id:'test-real',name:'<script>alert(1)</script>',host:'127.0.0.1',os:'linux',role:'Test server',model:'Virtual',rackId:rack.id,startU:1,units:2,watts:250,ports:[listener.address().port]};
  assert.equal((await request('/api/servers','POST',device)).status,201);
  assert.equal((await request('/api/servers/test-real/investigate','POST',{})).status,403);
  assert.equal((await request('/api/servers/test-real/repair','POST',{})).status,403);
  const repairHeaders={'X-NodeWatcher-Action':'repair'};
  assert.equal((await request('/api/servers/dc-01/investigate','POST',{},repairHeaders)).status,400);
  const rejectedPassword=['not','to','be','saved'].join('-');
  assert.equal((await request('/api/servers/test-real/investigate','POST',{host:'changed',password:rejectedPassword},repairHeaders)).status,409);
  assert.ok(!JSON.stringify((await request('/api/export')).body).includes(rejectedPassword));
  const laptop={...device,id:'test-laptop',name:'Test laptop',deviceType:'laptop',rackId:'',assignedUser:'LAB\\alex',location:'Desk 12'};
  assert.equal((await request('/api/servers','POST',laptop)).status,201);
  const userSnapshot={status:'collected',scope:'Console only',sessions:[{user:'LAB\\alex',connection:'Console'}]};
  const laptopResult={serverId:laptop.id,checkedAt:new Date().toISOString(),userSnapshot,checks:[{name:'Disk',status:'healthy',message:'OK'}]};
  assert.equal((await request('/api/import','POST',{version:1,results:[laptopResult]})).status,200);
  let endpointState=(await request('/api/state')).body;
  assert.equal(endpointState.servers.find(s=>s.id===laptop.id).assignedUser,laptop.assignedUser);
  assert.deepEqual(endpointState.results.find(r=>r.serverId===laptop.id).userSnapshot,userSnapshot);
  assert.equal((await request('/api/servers/test-laptop/placement','PATCH',{rackId:rack.id,startU:10})).status,400);
  assert.equal((await request('/api/servers/test-laptop','PUT',{...laptop,deviceType:'desktop',location:'Desk 15'})).status,200);
  assert.equal((await request('/api/export')).body.servers.find(s=>s.id===laptop.id).location,'Desk 15');
  const remoteHeaders={'X-InfraCheck-Action':'remote-access'};
  const remoteOptions={host:device.host,remotePort:listener.address().port,sshUser:'ops'};
  assert.equal((await request('/api/servers/test-real/connection-check','POST',remoteOptions)).status,403);
  assert.equal((await request('/api/servers/test-real/connect','POST',remoteOptions)).status,403);
  assert.equal((await request('/api/servers/dc-01/connect','POST',{host:'192.0.2.10'},remoteHeaders)).status,400);
  assert.equal((await request('/api/servers/test-real/connect','POST',{...remoteOptions,sshUser:'ops;whoami'},remoteHeaders)).status,400);
  assert.equal((await request('/api/servers/test-real/connection-check','POST',remoteOptions,{...remoteHeaders,Origin:'https://untrusted.example'})).status,403);
  const connection=await request('/api/servers/test-real/connection-check','POST',remoteOptions,remoteHeaders);
  assert.equal(connection.status,200);
  assert.equal(connection.body.canConnect,true);
  assert.equal(connection.body.target.protocol,'SSH');
  assert.equal(typeof connection.body.ping.reachable,'boolean');
  assert.ok(connection.body.command.includes(`-p ${listener.address().port}`));
  assert.equal((await request('/api/servers','POST',{...device,id:'overlap'})).status,400);
  assert.equal((await request('/api/servers/test-real','PUT',{...device,startU:42})).status,400);
  const result={serverId:device.id,checkedAt:'2026-01-01T00:00:00Z',checks:[{name:'Memory',status:'warning',category:'system',message:'85% used'}]};
  assert.equal((await request('/api/import','POST',{version:1,results:[result]})).status,200);
  const beforeMove=(await request('/api/state')).body;
  const moved=await request('/api/servers/test-real/placement','PATCH',{rackId:'rack-a02',startU:10});
  assert.equal(moved.status,200);
  assert.equal(moved.body.rackId,'rack-a02');
  assert.equal(moved.body.startU,10);
  assert.equal(moved.body.host,device.host);
  assert.deepEqual(moved.body.ports,device.ports);
  assert.deepEqual((await request('/api/state')).body.results,beforeMove.results);
  assert.equal((await request('/api/servers/test-real/placement','PATCH',{rackId:'rack-a01',startU:38})).status,400);
  assert.equal((await request('/api/servers/test-real/placement','PATCH',{rackId:'rack-a01',startU:42})).status,400);
  assert.equal((await request('/api/servers/test-real/placement','PATCH',{rackId:'missing',startU:1})).status,400);
  assert.equal((await request('/api/servers/test-real/placement','PATCH',{})).status,400);
  assert.equal((await request('/api/servers/missing/placement','PATCH',{rackId:rack.id,startU:1})).status,404);
  assert.equal((await request('/api/state')).body.servers.find(s=>s.id===device.id).startU,10);
  assert.equal((await request('/api/servers/test-real/placement','PATCH',{rackId:'rack-a02',startU:10})).status,200);
  const resized=await request('/api/servers/test-real/placement','PATCH',{rackId:'rack-a02',startU:10,units:8});
  assert.equal(resized.status,200);assert.equal(resized.body.units,8);
  assert.equal((await request('/api/servers/test-real/placement','PATCH',{rackId:'rack-a02',startU:20,units:8})).status,400);
  assert.equal((await request('/api/state')).body.servers.find(s=>s.id===device.id).units,8);
  const before=(await request('/api/state')).body;
  const badImport=await request('/api/import','POST',{version:1,racks:[{...rack,id:'atomic-rack'}],servers:[],results:[{...result,serverId:'missing'}]});
  assert.equal(badImport.status,400);
  assert.deepEqual((await request('/api/state')).body,before);
  const scan=await request('/api/servers/test-real/scan','POST');assert.equal(scan.status,200);
  assert.equal(scan.body.checks.find(c=>c.name==='Memory').status,'warning');
  assert.equal(scan.body.checks.find(c=>c.name===`TCP ${listener.address().port}`).status,'healthy');
  assert.equal(scan.body.systemCheckedAt,new Date(result.checkedAt).toISOString());
  const report=await request('/api/report');assert.equal(report.status,200);assert.ok(report.body.includes('&lt;script&gt;'));assert.ok(!report.body.includes('<script>'));
  assert.equal((await request('/api/export')).body.version,1);
  assert.equal((await request('/api/servers/test-real','PUT',{...device,host:'localhost'})).status,200);
  assert.equal((await request('/api/state')).body.results.some(r=>r.serverId==='test-real'),false);
  assert.equal((await request('/api/servers/test-real','DELETE')).status,200);
  const finalState=(await request('/api/state')).body;
  assert.equal(finalState.results.some(r=>r.serverId==='test-real'),false);
  assert.ok(finalState.changeHistory.some(c=>c.entityId==='test-real'&&c.action==='created'));
  assert.ok(finalState.changeHistory.some(c=>c.entityId==='test-real'&&c.action==='moved'&&c.changes.some(x=>x.field==='rackId')));
  assert.ok(finalState.changeHistory.some(c=>c.entityId==='test-real'&&c.action==='deleted'));
  assert.ok(!JSON.stringify(finalState.changeHistory).includes(rejectedPassword));
});
